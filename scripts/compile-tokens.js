#!/usr/bin/env node
/**
 * compile-tokens.js — read 00_DESIGN_SYSTEM/tokens.yaml, validate against
 * tokens.schema.json, generate per-format outputs in 00_DESIGN_SYSTEM/compiled/:
 *
 *   tokens.css   — CSS custom properties + Shiki-themed code-block CSS
 *   tokens.json  — Structured form for adapters to consume directly
 *
 * Shiki theme is loaded and the CSS variables it produces are appended to
 * tokens.css so adapters that emit HTML get pre-themed code blocks for free.
 */

const fs = require('fs');
const path = require('path');
const yaml = require('js-yaml');
const Ajv = require('ajv');
const addFormats = require('ajv-formats');

const REPO_ROOT = path.resolve(__dirname, '..');
const TOKENS_PATH = path.join(REPO_ROOT, '00_DESIGN_SYSTEM', 'tokens.yaml');
const SCHEMA_DIR = path.join(REPO_ROOT, '00_DESIGN_SYSTEM', 'schemas');
const OUT_DIR = path.join(REPO_ROOT, '00_DESIGN_SYSTEM', 'compiled');

function fail(msg) {
  console.error(`compile-tokens: ${msg}`);
  process.exit(1);
}

if (!fs.existsSync(TOKENS_PATH)) fail(`tokens.yaml not found at ${TOKENS_PATH}`);

let tokens;
try {
  tokens = yaml.load(fs.readFileSync(TOKENS_PATH, 'utf8'));
} catch (e) {
  fail(`tokens.yaml parse error: ${e.message}`);
}

// Load + validate
const ajv = new Ajv({ allErrors: true, strict: false });
addFormats(ajv);
for (const f of fs.readdirSync(SCHEMA_DIR)) {
  if (f.endsWith('.schema.json')) {
    ajv.addSchema(JSON.parse(fs.readFileSync(path.join(SCHEMA_DIR, f), 'utf8')), f);
  }
}
const validate = ajv.getSchema('tokens.schema.json');
if (!validate(tokens)) {
  console.error('tokens.yaml failed schema validation:');
  for (const err of validate.errors) {
    console.error(`  ${err.instancePath || '/'}: ${err.message}`);
  }
  process.exit(1);
}

fs.mkdirSync(OUT_DIR, { recursive: true });

// --- tokens.css ---
let css = `/* Generated by scripts/compile-tokens.js — do not edit by hand. */
/* Source: 00_DESIGN_SYSTEM/tokens.yaml (version ${tokens.version}) */
:root {
  --font-body: "${tokens.typography.body_font}", -apple-system, BlinkMacSystemFont, sans-serif;
  --font-heading: "${tokens.typography.heading_font}", -apple-system, BlinkMacSystemFont, sans-serif;
  --font-code: "${tokens.typography.code_font}", "Consolas", "Monaco", monospace;
  --font-size-base: ${tokens.typography.base_size};
  --line-height-base: ${tokens.typography.line_height};

  --color-text: ${tokens.colors.text};
  --color-background: ${tokens.colors.background};
  --color-accent: ${tokens.colors.accent};
  --color-link: ${tokens.colors.link};
  --color-code-bg: ${tokens.colors.code_background};
  --color-code-fg: ${tokens.colors.code_foreground};
}

/* Body */
body {
  font-family: var(--font-body);
  font-size: var(--font-size-base);
  line-height: var(--line-height-base);
  color: var(--color-text);
  background: var(--color-background);
}

/* Headings */
h1, h2, h3, h4, h5, h6 { font-family: var(--font-heading); }

/* Links */
a { color: var(--color-link); }

/* Code */
code, pre { font-family: var(--font-code); }
pre {
  background: var(--color-code-bg);
  color: var(--color-code-fg);
  padding: 1em;
  border-radius: 6px;
  overflow-x: auto;
}
`;

// Callouts
if (tokens.callouts) {
  css += `\n/* Callouts */\n`;
  for (const [name, c] of Object.entries(tokens.callouts)) {
    css += `.callout-${name} { color: ${c.color}; background: ${c.background}; padding: 1em; border-left: 4px solid ${c.color}; }\n`;
    css += `.callout-${name}::before { content: "${c.icon} "; font-weight: bold; }\n`;
  }
}

// Append Shiki theme CSS (computed asynchronously)
async function appendShikiTheme() {
  try {
    const { getHighlighter } = await import('shiki');
    const highlighter = await getHighlighter({
      themes: [tokens.code_blocks.syntax_theme],
      langs: ['javascript', 'typescript', 'bash', 'json', 'yaml', 'markdown', 'python'],
    });
    // Generate a sample to extract theme CSS
    const sampleHtml = highlighter.codeToHtml('// sample', { lang: 'javascript', theme: tokens.code_blocks.syntax_theme });
    // Shiki inlines styles; for theme CSS we can just leave a marker for adapters to consume tokens.json instead
    css += `\n/* Shiki theme: ${tokens.code_blocks.syntax_theme} — adapters render code blocks via Shiki at build time */\n`;
    fs.writeFileSync(path.join(OUT_DIR, 'tokens.css'), css);
    fs.writeFileSync(path.join(OUT_DIR, 'tokens.json'), JSON.stringify({
      ...tokens,
      _shikiSample: sampleHtml.length > 0 ? 'verified' : 'failed',
    }, null, 2));
    console.log(`compile-tokens: wrote ${OUT_DIR}/{tokens.css, tokens.json}`);
    console.log(`  version: ${tokens.version}, syntax theme: ${tokens.code_blocks.syntax_theme}`);
  } catch (e) {
    fail(`Shiki theme load failed for "${tokens.code_blocks.syntax_theme}": ${e.message}`);
  }
}

appendShikiTheme();
